package org.YavSoft.UniBoard.predict

/**
 * 日常高频词表。
 *
 * 内置词库按 jieba 词频排序，但一些口语高频词（好的、可以、谢谢…）
 * 在书面语料里权重偏低，候选里常被生僻词挤下去。这里单独给它们加权，
 * 让「日常用语优先」这个直觉成立。
 */
object DailyWords {

    private val WORDS: Set<String> = setOf(
        "的", "了", "我", "你", "他", "她", "它", "我们", "你们", "他们",
        "是", "不", "在", "有", "就", "都", "也", "很", "还", "把",
        "好", "好的", "行", "可以", "没问题", "行吧", "是的", "对的",
        "谢谢", "多谢", "感谢", "不客气", "对不起", "抱歉", "没事", "没关系",
        "请问", "请", "麻烦", "帮忙", "稍等", "等一下", "马上", "现在",
        "今天", "明天", "昨天", "早上", "中午", "晚上", "晚安", "早安",
        "吃饭", "喝水", "睡觉", "上班", "下班", "回家", "在吗", "在不在",
        "什么", "怎么", "为什么", "哪里", "哪儿", "多少", "几个", "哪个",
        "知道", "不知道", "觉得", "认为", "希望", "需要", "应该", "可能",
        "一下", "一点", "有点", "非常", "特别", "真的", "确实", "当然",
        "因为", "所以", "但是", "不过", "然后", "还有", "或者", "如果",
        "这个", "那个", "这些", "那些", "这样", "那样", "这里", "那里",
        "时候", "东西", "事情", "问题", "方法", "地方", "手机", "电脑",
        "工作", "学习", "生活", "朋友", "家人", "孩子", "老婆", "老公",
        "收到", "明白", "了解", "确认", "同意", "好的呢", "收到啦",
        "哈哈", "哈哈哈", "呵呵", "嗯", "嗯嗯", "哦", "好呢", "好的呀"
    )

    fun contains(word: String): Boolean = WORDS.contains(word)

    /** 命中日常词时的加分 */
    fun bonus(word: String): Double = if (WORDS.contains(word)) 9.0 else 0.0
}
